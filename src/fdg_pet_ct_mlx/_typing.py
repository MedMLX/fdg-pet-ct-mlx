"""Structural types for the subset of ``mlx.core`` used by this package.

The synthesis and blur functions take the MLX module as an explicit ``mx`` argument. Pass
``mlx.core`` itself (or the module returned by ``medmlx_core.runtime.import_mlx``).
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from mlx.core import Dtype, array


class RandomRuntime(Protocol):
    """The ``mx.random`` functions used for seeded noise."""

    def key(self, seed: int) -> array: ...
    def normal(
        self, shape: Sequence[int], dtype: Dtype, *, key: array | None = None
    ) -> array: ...


class FdgRuntime(Protocol):
    """The ``mlx.core`` dtypes and operations used by the FDG kernels."""

    @property
    def array(self) -> type[array]: ...
    @property
    def float32(self) -> Dtype: ...
    @property
    def int32(self) -> Dtype: ...
    @property
    def int64(self) -> Dtype: ...
    @property
    def uint32(self) -> Dtype: ...
    @property
    def complex64(self) -> Dtype: ...
    @property
    def bool_(self) -> Dtype: ...
    @property
    def random(self) -> RandomRuntime: ...
    def eval(self, *args: array) -> None: ...
    def zeros(self, shape: Sequence[int], *, dtype: Dtype) -> array: ...
    def ones(self, shape: Sequence[int], *, dtype: Dtype) -> array: ...
    def full(self, shape: Sequence[int], vals: float, *, dtype: Dtype) -> array: ...
    def reshape(self, a: array, /, shape: Sequence[int]) -> array: ...
    def zeros_like(self, a: array, /) -> array: ...
    def arange(self, start: int, stop: int, *, dtype: Dtype) -> array: ...
    def all(self, a: array, /) -> array: ...
    def isfinite(self, a: array, /) -> array: ...
    def min(self, a: array, /) -> array: ...
    def max(self, a: array, /) -> array: ...
    def sum(self, a: array, /) -> array: ...
    def mean(self, a: array, /) -> array: ...
    def floor(self, a: array, /) -> array: ...
    def exp(self, a: array, /) -> array: ...
    def sqrt(self, a: array, /) -> array: ...
    def clip(self, a: array, /, a_min: float, a_max: float) -> array: ...
    def maximum(self, a: array, b: array | float, /) -> array: ...
    def where(self, condition: array, x: array, y: array | int, /) -> array: ...
    def logical_or(self, a: array, b: array, /) -> array: ...
    def logical_and(self, a: array, b: array, /) -> array: ...
    def moveaxis(self, a: array, /, source: int, destination: int) -> array: ...
    def pad(self, a: array, pad_width: list[tuple[int, int]]) -> array: ...
    def conv1d(self, input: array, weight: array, /) -> array: ...
    def conv3d(self, input: array, weight: array, /) -> array: ...
